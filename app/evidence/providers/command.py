"""Generic command capabilities: command lines AI Studio already knows, or that are explicitly
declared - never generated by a model.

Sources
  phase_verification  the current phase's verification commands (they already ran in VERIFYING)
  run_history         verification commands of the other phases of this run
  settings            commands the user configured (Settings -> Orchestration -> evidence commands)
  repository          declared in repository metadata: AI Studio's generic manifest
                      (.aistudio/evidence.json: commands and services) and declared-script readers
                      (package.json scripts)

Confidence
  CONFIRMED    the command actually ran in this run
  INFERRED     declared and its program resolves, but not run yet
  UNAVAILABLE  explicitly checked and unusable: program not found, destructive, persistent side
               effects, long-running without a service declaration, command execution disabled

Execution runs the declared command line only. Arguments are accepted only by capabilities that
declare them, and every argument must match the declared pattern. Services (declared in the
manifest) are long-running and follow the lifecycle start -> ready -> capture -> stop, with a
validated readiness probe (readiness.py). A failing build-kind command is reduced to compact
diagnostics (diagnostics.py); the full output stays an artifact.

Provenance: each capability records where it was declared (and that file's hash), whether the worker
changed that file in this phase, and the resolved executable. A declared command that runs a repository
script (a verification helper the worker may have written) records the script's content hash in its
definition: the harness runs the script itself and judges its output - the worker's report of what the
script printed is never evidence - and a changed script makes the earlier results of that command stale.

A command that exits 0 without the output the plan expected has cause "unobserved": the product may lack
the property, or the command may simply not report it. A bounded replan may then choose a capability that
observes it (the requirement stays FAILED unless something actually observes it).
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
from collections import deque
from typing import Any, Callable

from app.evidence import readiness as rd
from app.evidence.diagnostics import BuildLogReducer
from app.evidence.lifecycle import ServiceProcess
from app.evidence.model import CONFIRMED, FAILED, INFERRED, PASSED, TIMEOUT, UNAVAILABLE, Capability, PlanStep
from app.evidence.providers.base import CapabilityProvider, DiscoveryContext, ExecContext, StepOutcome
from app.orchestration.safety import destructive_reason
from app.workers.process_runner import ProcessLaunchError, ProcessRunner

MANIFEST = ".aistudio/evidence.json"
MAX_MANIFEST_BYTES = 64 * 1024
MAX_PACKAGE_BYTES = 256 * 1024
MAX_DECLARED = 40
DEFAULT_TIMEOUT = 180
DEFAULT_ARG_PATTERN = r"[A-Za-z0-9_.:/=@+-]{1,120}"
_UNSAFE_ARG = re.compile(r"[\"'`%!^&|<>;$\r\n()]")
# Declared scripts whose name or body suggests persistent side effects are never offered.
_SIDE_EFFECTS = re.compile(r"\b(publish|deploy|release|push|upload|clean|purge|reset|format|fix|install|uninstall|"
                           r"update|upgrade|migrate|seed|prune|eject|commit)\b|--(?:write|fix)\b", re.IGNORECASE)
# Long-running scripts cannot be run to completion; they may be declared as services instead.
_LONG_RUNNING = re.compile(r"^(start|dev|serve|watch|preview)\b", re.IGNORECASE)
_STATIC = re.compile(r"\b(lint|eslint|flake8|ruff|mypy|pylint|typecheck|type-check|clippy|vet)\b|--noEmit\b",
                     re.IGNORECASE)
_TEST = re.compile(r"\b(tests?|spec|pytest|jest|vitest|mocha|ctest|e2e|smoke|acceptance|check)\b", re.IGNORECASE)
_BUILD = re.compile(r"\b(build|compile|bundle|tsc|msbuild|cmake|make|ninja|gradlew?|mvn|cargo\s+build|"
                    r"dotnet\s+build)\b", re.IGNORECASE)
_SHELL_BUILTINS = frozenset({"echo", "cd", "set", "type", "dir", "call", "if", "for", "exit", "ver", "true", "false"})
_NOT_FOUND_EXIT = frozenset({9009, 127})  # cmd.exe / POSIX shells: the program does not exist


def classify_command(text: str) -> str:
    """A semantic kind from the command's own words (generic tool vocabulary, no project types)."""
    if _STATIC.search(text):
        return "static_analysis"
    if _TEST.search(text):
        return "automated_test"
    if _BUILD.search(text):
        return "build"
    return "command_execution"


def _program(command: str) -> str:
    s = command.strip()
    if s.startswith('"'):
        return s[1:].split('"', 1)[0]
    return s.split()[0] if s else ""


def _short(text: str, n: int = 80) -> str:
    t = " ".join(str(text).split())
    return t if len(t) <= n else t[:n - 3] + "..."


def file_sha1(path: str, limit: int = 4 * 1024 * 1024) -> str:
    try:
        with open(path, "rb") as f:
            return hashlib.sha1(f.read(limit)).hexdigest()[:16]
    except OSError:
        return ""


def declared_provenance(ctx: DiscoveryContext, rel: str) -> dict[str, Any]:
    """Where a capability was declared: the file, its content hash, and whether the worker changed it in this
    phase (then the check it is judged by was written by the worker itself - Claude is told)."""
    rel = rel.replace("\\", "/")
    changed = {str(p).replace("\\", "/") for p in ctx.changed_files or []}
    return {"declared_in": rel, "declared_sha1": file_sha1(os.path.join(ctx.repo_path, *rel.split("/"))),
            "changed_in_phase": rel in changed}


def script_inputs(ctx: DiscoveryContext, command: str, limit: int = 4) -> dict[str, str]:
    """Repository files a declared command runs (e.g. `cmd /c Scripts/verify.bat`, `python tools/check.py`):
    {relative path: content hash}. Only existing files inside the repository count; nothing is executed."""
    root = os.path.abspath(ctx.repo_path)
    out: dict[str, str] = {}
    for tok in re.findall(r'"([^"]+)"|(\S+)', command):
        t = (tok[0] or tok[1]).strip()
        if not t or t.startswith("-") or len(t) > 260 or "\0" in t:
            continue
        full = os.path.abspath(t if os.path.isabs(t) else os.path.join(root, t))
        if not full.startswith(root + os.sep) or not os.path.isfile(full):
            continue
        rel = os.path.relpath(full, root).replace("\\", "/")
        if rel.split("/")[0].lower() == ".git":
            continue
        out[rel] = file_sha1(full)
        if len(out) >= limit:
            break
    return out


class CommandProvider(CapabilityProvider):
    name = "command"
    version = "2"

    def __init__(self, which: Callable[[str], str | None] = shutil.which):
        self.which = which
        self.last_notes: list[str] = []

    # ------------------------------------------------------------ discovery

    def _resolve(self, command: str, cwd: str) -> str:
        """The resolved program ("" = not found; "(shell builtin)" for builtins)."""
        prog = _program(command)
        if not prog:
            return ""
        if prog.lower() in _SHELL_BUILTINS:
            return "(shell builtin)"
        if os.path.isabs(prog) or "/" in prog or "\\" in prog:
            full = prog if os.path.isabs(prog) else os.path.join(cwd, prog)
            return full if os.path.exists(full) else ""
        return str(self.which(prog) or "")

    def _resolves(self, command: str, cwd: str) -> bool:
        return bool(self._resolve(command, cwd))

    def _cap(self, ctx: DiscoveryContext, command: str, source: str, name: str, *, kind: str = "",
             description: str = "", timeout: int = 0, accepts_args: bool = False, arg_pattern: str = "",
             max_args: int = 4, lifecycle: str = "oneshot", ready_output: str = "", ready_timeout: int = 0,
             unavailable: str = "", readiness: Any = None, provenance: dict[str, Any] | None = None) -> Capability:
        command = command.strip()
        o = ctx.settings
        ran = ctx.ran_commands.get(command)
        reason = unavailable or (f"needs user approval ({destructive_reason(command)})" if destructive_reason(command)
                                 else "")
        spec: dict[str, Any] = {}
        if lifecycle == "service" and not reason:
            spec, why = rd.parse_readiness(readiness, legacy_marker=ready_output,
                                           default_timeout=float(ready_timeout or 60))
            if why:
                reason = f"invalid readiness declaration: {why}"
        if not reason and o is not None and not getattr(o, "run_verification_commands", True):
            reason = "command execution is disabled in the settings"
        exe = self._resolve(command, ctx.repo_path) if not reason else ""
        if reason:
            confidence = UNAVAILABLE
        elif ran is not None and not ran.skipped_reason and lifecycle == "oneshot":
            confidence = CONFIRMED
            reason = "ran in this run: " + ("timed out" if ran.exit_code is None else f"exit {ran.exit_code}")
        elif not exe:
            confidence, reason = UNAVAILABLE, f"program {_program(command)!r} not found"
        else:
            confidence = INFERRED
            reason = "declared; program found; not run yet" if lifecycle == "oneshot" else \
                "declared service; program found; it is only started while evidence is collected"
        constraints: dict[str, Any] = {"timeout_seconds": int(timeout or DEFAULT_TIMEOUT), "interactive": False,
                                       "lifecycle": lifecycle, "accepts_args": bool(accepts_args)}
        details: dict[str, Any] = {"command": command}
        if accepts_args:
            constraints["max_args"] = max(1, min(int(max_args or 4), 8))
            details["arg_pattern"] = arg_pattern or DEFAULT_ARG_PATTERN
        if lifecycle == "service":
            constraints["ready_output"] = ready_output
            constraints["ready_timeout_seconds"] = int(ready_timeout or 60)
            if spec and (readiness not in (None, "", {})):  # only an explicit declaration changes the definition
                constraints["readiness"] = spec
        prov = dict(provenance or {})
        prov.setdefault("source_detail", source)
        if exe:
            prov["executable"] = exe
        return Capability(id="", kind=kind or classify_command(command), name=name[:120],
                          description=(description or f"runs `{_short(command, 160)}`")[:400], source=source,
                          confidence=confidence, provider=self.name,
                          key=f"{'service' if lifecycle == 'service' else 'command'}:{command}",
                          constraints=constraints, details=details, reason=reason, provenance=prov)

    async def discover(self, ctx: DiscoveryContext) -> list[Capability]:
        self.last_notes = []
        caps: list[Capability] = []
        seen: set[str] = set()

        def add(cap: Capability) -> None:
            if cap.key not in seen:
                seen.add(cap.key)
                caps.append(cap)

        phase = ctx.phase
        for cmd in getattr(phase, "verification_commands", []) or []:
            if cmd.strip():
                add(self._cap(ctx, cmd, "phase_verification", f"phase verification: {_short(cmd)}",
                              provenance={"declared_in": f"phase {getattr(phase, 'id', '')} plan"}))
        for p in ctx.phases:
            if p is not phase:
                for cmd in getattr(p, "verification_commands", []) or []:
                    if cmd.strip():
                        add(self._cap(ctx, cmd, "run_history", f"{p.id} verification: {_short(cmd)}",
                                      provenance={"declared_in": f"phase {p.id} plan"}))
        for cmd in getattr(ctx.settings, "evidence_commands", []) or []:  # one command line per entry
            if str(cmd).strip():
                add(self._cap(ctx, str(cmd), "settings", f"configured: {_short(cmd)}",
                              provenance={"declared_in": "AI Studio settings"}))
        for cap in self._manifest(ctx):
            add(cap)
        for cap in self._package_scripts(ctx):
            add(cap)
        return caps

    def _read_json(self, path: str, limit: int) -> Any:
        if not os.path.isfile(path):
            return None
        if os.path.getsize(path) > limit:
            self.last_notes.append(f"{os.path.basename(path)} is larger than {limit} bytes; not read")
            return None
        try:
            with open(path, encoding="utf-8") as f:
                return json.load(f)
        except (OSError, ValueError) as exc:
            self.last_notes.append(f"{os.path.basename(path)} unreadable: {exc}"[:200])
            return None

    def _manifest(self, ctx: DiscoveryContext) -> list[Capability]:
        """AI Studio's generic repository declaration of evidence commands and services."""
        data = self._read_json(os.path.join(ctx.repo_path, *MANIFEST.split("/")), MAX_MANIFEST_BYTES)
        if not isinstance(data, dict):
            return []
        prov = declared_provenance(ctx, MANIFEST)
        out: list[Capability] = []
        for section, lifecycle in (("commands", "oneshot"), ("services", "service")):
            for d in (data.get(section) or [])[:MAX_DECLARED]:
                if not isinstance(d, dict) or not str(d.get("command") or "").strip():
                    continue
                cmd = str(d["command"])
                kind = re.sub(r"[^a-z0-9]+", "_", str(d.get("kind") or "").lower()).strip("_")
                if lifecycle == "service" and not kind:
                    kind = "runtime_launch"
                c = self._cap(
                    ctx, cmd, "repository", str(d.get("name") or _short(cmd)), kind=kind,
                    description=str(d.get("description") or ""), timeout=int(d.get("timeout_seconds") or 0),
                    accepts_args=bool(d.get("accepts_args")), arg_pattern=str(d.get("arg_pattern") or ""),
                    max_args=int(d.get("max_args") or 4), lifecycle=lifecycle,
                    ready_output=str(d.get("ready_output") or ""),
                    ready_timeout=int(d.get("ready_timeout_seconds") or 0), readiness=d.get("readiness"),
                    provenance=dict(prov))
                scripts = script_inputs(ctx, cmd)
                if scripts:  # part of the definition: a changed script makes earlier results of it stale
                    c.details["scripts"] = scripts
                    changed = {str(x).replace("\\", "/") for x in ctx.changed_files or []}
                    if changed & set(scripts):
                        c.provenance["changed_in_phase"] = True
                        c.provenance["scripts_changed_in_phase"] = sorted(changed & set(scripts))
                out.append(c)
        return out

    def _package_scripts(self, ctx: DiscoveryContext) -> list[Capability]:
        """Declared scripts of a package.json manifest (a declared-script reader; add more readers here)."""
        data = self._read_json(os.path.join(ctx.repo_path, "package.json"), MAX_PACKAGE_BYTES)
        scripts = data.get("scripts") if isinstance(data, dict) else None
        if not isinstance(scripts, dict):
            return []
        prov = declared_provenance(ctx, "package.json")
        runner = bool(self.which("npm"))
        out: list[Capability] = []
        for name, body in list(scripts.items())[:MAX_DECLARED]:
            name, body = str(name), str(body)
            unavailable = ""
            if _LONG_RUNNING.match(name) or "--watch" in body:
                unavailable = f"long-running script; declare it as a service in {MANIFEST} to use it"
            elif _SIDE_EFFECTS.search(name) or _SIDE_EFFECTS.search(body) or destructive_reason(body):
                unavailable = "may have persistent side effects"
            elif not runner:
                unavailable = "program 'npm' not found"
            out.append(self._cap(ctx, f"npm run {name}", "repository", f"package script: {name}",
                                 kind=classify_command(f"{name} {body}"),
                                 description=f"package.json script `{name}`: {_short(body, 160)}",
                                 unavailable=unavailable, provenance=dict(prov)))
        return out

    # ------------------------------------------------------------ validation / execution

    @staticmethod
    def command_line(cap: Capability, step: PlanStep) -> str:
        cmd = str(cap.details.get("command") or "")
        return cmd + ("".join(f" {a}" for a in step.args) if step.args else "")

    def validate(self, cap: Capability, step: PlanStep) -> str:
        if cap.constraints.get("lifecycle") == "service":
            return f"{cap.id} is a service: list it under `resources` (it is started and stopped around the steps)"
        if step.args:
            if not cap.constraints.get("accepts_args"):
                return f"{cap.id} does not accept arguments"
            if len(step.args) > int(cap.constraints.get("max_args") or 4):
                return f"{cap.id} accepts at most {cap.constraints.get('max_args')} argument(s)"
            try:
                pattern = re.compile(str(cap.details.get("arg_pattern") or DEFAULT_ARG_PATTERN))
            except re.error:
                return f"{cap.id} declares an invalid argument pattern"
            for a in step.args:
                if _UNSAFE_ARG.search(a) or not pattern.fullmatch(a):
                    return f"argument {a!r} does not match the pattern {cap.id} declares"
        reason = destructive_reason(self.command_line(cap, step))
        return f"needs user approval ({reason})" if reason else ""

    async def execute(self, cap: Capability, step: PlanStep, ctx: ExecContext) -> StepOutcome:
        cmd = self.command_line(cap, step)
        if self.validate(cap, step):  # defence in depth: validated again right before running
            return StepOutcome(UNAVAILABLE, reason=self.validate(cap, step))
        return await run_command(cmd, step, ctx, build=cap.kind == "build")

    # ------------------------------------------------------------ lifecycle (declared services)

    def supports_lifecycle(self, cap: Capability) -> bool:
        return cap.constraints.get("lifecycle") == "service"

    async def start(self, cap: Capability, ctx: ExecContext) -> ServiceProcess:
        cmd = str(cap.details.get("command") or "")
        if destructive_reason(cmd):
            raise RuntimeError(f"needs user approval ({destructive_reason(cmd)})")
        sp = ServiceProcess(cmd, ctx.repo_path, ctx.max_capture_bytes)
        spec = service_readiness(cap)
        await sp.start([str(spec.get("text") or cap.constraints.get("ready_output") or "")])
        return sp

    async def ready(self, handle: ServiceProcess, cap: Capability, ctx: ExecContext) -> tuple[str, str]:
        declared = float(cap.constraints.get("ready_timeout_seconds") or ctx.ready_timeout)
        return await rd.wait_ready(handle, service_readiness(cap), min(declared, ctx.ready_timeout), ctx.repo_path)

    def capture(self, handle: ServiceProcess) -> str:
        return handle.output()

    async def stop(self, handle: ServiceProcess) -> None:
        await handle.stop()


def service_readiness(cap: Capability) -> dict[str, Any]:
    """The capability's readiness probe (an explicit declaration, else the legacy output marker / alive)."""
    spec = cap.constraints.get("readiness")
    if isinstance(spec, dict) and spec.get("kind"):
        return spec
    parsed, _why = rd.parse_readiness(None, legacy_marker=str(cap.constraints.get("ready_output") or ""),
                                      default_timeout=float(cap.constraints.get("ready_timeout_seconds") or 60))
    return parsed


async def run_command(cmd: str | list[str], step: PlanStep, ctx: ExecContext, *, build: bool = False,
                      cwd: str = "", reducer: BuildLogReducer | None = None,
                      on_line: Callable[[str], None] | None = None) -> StepOutcome:
    """Run ONE validated command line - or an argv list built from validated paths (no shell) - with bounded
    output (the tail is kept). A build's diagnostics are reduced while streaming, so its root errors survive
    even when only the tail of a huge log is kept."""
    kept: deque[str] = deque()
    size = [0, 0]  # kept bytes, total bytes
    if reducer is None and build:
        reducer = BuildLogReducer(root=ctx.repo_path)
    label = cmd if isinstance(cmd, str) else " ".join([os.path.basename(cmd[0]), *cmd[1:]]) if cmd else ""
    # A build log is kept whole up to the artifact limit - its HEAD (where the root errors are) and its tail -
    # instead of only the tail; the prompts still only receive the reduced diagnostics.
    budget = max(ctx.max_capture_bytes, ctx.max_artifact_bytes - 256) if reducer is not None else ctx.max_capture_bytes
    head: list[str] = []
    head_size = [0]

    def collect(line: str) -> None:
        n = len(line) + 1
        size[1] += n
        if reducer is not None and head_size[0] + n <= budget // 2:
            head.append(line)
            head_size[0] += n
        else:
            kept.append(line)
            size[0] += n
            while size[0] > budget - head_size[0] and len(kept) > 1:
                size[0] -= len(kept.popleft()) + 1
        if reducer is not None:
            reducer.feed(line)
        if on_line is not None:
            on_line(line)

    runner = ProcessRunner(grace_seconds=2)
    try:
        if isinstance(cmd, list):
            res = await runner.run(cmd, cwd=cwd or ctx.repo_path, timeout=ctx.timeout, on_stdout=collect,
                                   on_stderr=collect, capture_limit=64 * 1024)
        else:
            res = await runner.run_shell(cmd, cwd=cwd or ctx.repo_path, timeout=ctx.timeout, on_stdout=collect,
                                         on_stderr=collect, capture_limit=64 * 1024)
    except ProcessLaunchError as exc:
        return StepOutcome(UNAVAILABLE, reason=f"could not start: {exc}"[:300], cause="strategy")
    truncated = size[1] > size[0] + head_size[0]
    if head:
        omitted = size[1] - size[0] - head_size[0]
        out = "\n".join(head) + (f"\n...[{omitted} bytes of output omitted]...\n" if truncated else "\n") + \
            "\n".join(kept)
    else:
        out = ("...[output truncated: showing the end]...\n" if truncated else "") + "\n".join(kept)
    last = next((x.strip() for x in reversed(kept) if x.strip()), "") or \
        next((x.strip() for x in reversed(head) if x.strip()), "")
    base: dict[str, Any] = dict(output=out, truncated=truncated, duration=res.duration)
    if res.timed_out:
        return StepOutcome(TIMEOUT, None, summary=f"`{_short(label)}` timed out after {ctx.timeout:.0f}s",
                           reason="timeout", **base)
    code = res.exit_code
    if code in _NOT_FOUND_EXIT:
        return StepOutcome(UNAVAILABLE, code, summary=f"`{_short(label)}`: program not found (exit {code})",
                           reason="the command's program was not found", cause="strategy", **base)
    if reducer is not None and (code != 0 or reducer.s.error_count):
        s = reducer.summary()
        base.update(diagnostics=s.lines(6), details={"build": {k: v for k, v in s.to_dict(6).items()
                                                               if k != "lines_scanned"}})
    if step.fail_output and step.fail_output in out:
        return StepOutcome(FAILED, code, summary=f"`{_short(label)}` printed the failure marker "
                                                 f"{step.fail_output!r}", reason="failure marker found", **base)
    if code != 0:
        diags = base.get("diagnostics") or []
        first = diags[1] if len(diags) > 1 else None
        return StepOutcome(FAILED, code, summary=f"`{_short(label)}` exited {code}: {_short(first or last, 160)}",
                           reason=f"exit {code}", **base)
    if step.expect_output and step.expect_output not in out:
        return StepOutcome(FAILED, code, summary=f"`{_short(label)}` exited 0 but the expected output "
                                                 f"{step.expect_output!r} did not appear",
                           reason="expected output missing", cause="unobserved", **base)
    return StepOutcome(PASSED, code, summary=f"`{_short(label)}` exited 0"
                       + (f" and printed {step.expect_output!r}" if step.expect_output else "")
                       + (f": {_short(last, 120)}" if last else ""), **base)
