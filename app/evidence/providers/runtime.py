"""Generic interactive runtime provider: applications the project DECLARES as runnable, observed while
they run - no technology is assumed (a web server, a desktop app, a game, a CLI daemon all look alike).

Declared in the repository's AI Studio manifest (.aistudio/evidence.json):

    "runtimes": [{
        "name": "app", "command": "<how to start it>", "cwd": "<optional repo-relative dir>",
        "readiness": {"kind": "tcp_port", "port": 5173},          (readiness.py; default: process alive)
        "ready_timeout_seconds": 60,
        "endpoints": [{"name": "health", "url": "http://127.0.0.1:5173/health", "expected_status": 200}],
        "actions":   [{"name": "smoke", "command": "node smoke.mjs", "kind": "runtime_behavior"}],
        "logs":      [{"name": "server log", "path": "logs/server.log"}]
    }]

Capabilities per runtime (keys runtime:<name>[:...]):
    runtime_launch   lifecycle resource: start -> readiness probe -> capture -> stop
    runtime_ready    re-probe readiness while it runs            (observes the running resource)
    runtime_log      bounded capture of its output + declared log files, checked for literal markers
    process_control  is it still running (no crash)?
    local_endpoint   GET a declared local URL (status + optional literal text)
    <declared kind>  a declared verification action run while it runs

Every observing capability declares `requires_resource`: the plan must start the runtime for that
requirement, and the step receives the running handle - which is also how other providers (e.g. a
capture provider) can observe the same application. Nothing here is generated by a model: commands,
URLs and paths all come from the declaration and are validated.
"""
from __future__ import annotations

import asyncio
import os
import re
import shutil
import time
from typing import Any, Callable

from app.evidence import readiness as rd
from app.evidence.lifecycle import ServiceProcess
from app.evidence.model import FAILED, INFERRED, PASSED, UNAVAILABLE, Capability, PlanStep
from app.evidence.providers.base import CapabilityProvider, DiscoveryContext, ExecContext, StepOutcome
from app.evidence.providers.command import MANIFEST, MAX_MANIFEST_BYTES, _program, _short, declared_provenance, \
    run_command
from app.orchestration.safety import destructive_reason

MAX_RUNTIMES = 8
MAX_PER_RUNTIME = 8
MAX_LOG_BYTES = 64 * 1024
_NAME = re.compile(r"[^A-Za-z0-9_.-]+")


def _slug(s: str) -> str:
    return _NAME.sub("-", str(s or "").strip()).strip("-")[:40] or "x"


def _kind(v: Any, default: str) -> str:
    k = re.sub(r"[^a-z0-9]+", "_", str(v or "").lower()).strip("_")
    return k or default


def _tail_file(path: str, limit: int = MAX_LOG_BYTES) -> str:
    try:
        with open(path, "rb") as f:
            f.seek(0, os.SEEK_END)
            size = f.tell()
            f.seek(max(0, size - limit))
            data = f.read(limit)
        return ("...[earlier log dropped]...\n" if size > limit else "") + data.decode("utf-8", errors="replace")
    except OSError as exc:
        return f"(log unreadable: {exc})"


class RuntimeProvider(CapabilityProvider):
    name = "runtime"
    version = "1"

    def __init__(self, which: Callable[[str], str | None] = shutil.which):
        self.which = which
        self.last_notes: list[str] = []

    # ------------------------------------------------------------ discovery

    def _resolve(self, command: str, cwd: str) -> str:
        prog = _program(command)
        if not prog:
            return ""
        if os.path.isabs(prog) or "/" in prog or "\\" in prog:
            full = prog if os.path.isabs(prog) else os.path.join(cwd, prog)
            return full if os.path.exists(full) else ""
        return str(self.which(prog) or "")

    async def discover(self, ctx: DiscoveryContext) -> list[Capability]:
        self.last_notes = []
        path = os.path.join(ctx.repo_path, *MANIFEST.split("/"))
        if not os.path.isfile(path):
            return []
        if os.path.getsize(path) > MAX_MANIFEST_BYTES:
            self.last_notes.append(f"{MANIFEST} is larger than {MAX_MANIFEST_BYTES} bytes; not read")
            return []
        try:
            import json
            with open(path, encoding="utf-8") as f:
                data = json.load(f)
        except (OSError, ValueError) as exc:
            self.last_notes.append(f"{MANIFEST} unreadable: {exc}"[:200])
            return []
        runtimes = data.get("runtimes") if isinstance(data, dict) else None
        if not isinstance(runtimes, list):
            return []
        prov = declared_provenance(ctx, MANIFEST)
        caps: list[Capability] = []
        for d in runtimes[:MAX_RUNTIMES]:
            if isinstance(d, dict) and str(d.get("name") or "").strip() and str(d.get("command") or "").strip():
                caps += self._runtime(ctx, d, prov)
        return caps

    def _runtime(self, ctx: DiscoveryContext, d: dict[str, Any], prov: dict[str, Any]) -> list[Capability]:
        name, cmd = str(d["name"]).strip()[:60], str(d["command"]).strip()
        key = f"runtime:{_slug(name)}"
        cwd_rel = str(d.get("cwd") or "").strip()
        cwd = ""
        why = ""
        if cwd_rel:
            if not rd.relative_path_ok(cwd_rel) or not os.path.isdir(os.path.join(ctx.repo_path, cwd_rel)):
                why = f"cwd {cwd_rel!r} must be an existing repository-relative directory"
            else:
                cwd = cwd_rel
        if not why and destructive_reason(cmd):
            why = f"needs user approval ({destructive_reason(cmd)})"
        o = ctx.settings
        if not why and o is not None and not getattr(o, "run_verification_commands", True):
            why = "command execution is disabled in the settings"
        ready_timeout = int(d.get("ready_timeout_seconds") or 60)
        spec, bad = rd.parse_readiness(d.get("readiness"), legacy_marker=str(d.get("ready_output") or ""),
                                       default_timeout=float(ready_timeout))
        if not why and bad:
            why = f"invalid readiness declaration: {bad}"
        exe = self._resolve(cmd, os.path.join(ctx.repo_path, cwd) if cwd else ctx.repo_path) if not why else ""
        if not why and not exe:
            why = f"program {_program(cmd)!r} not found"
        base_conf = UNAVAILABLE if why else INFERRED
        runtime_reason = why or "declared runtime; program found; started only while evidence is collected"
        p = dict(prov, source_detail="repository runtime declaration", runtime=name, **({"executable": exe} if exe
                                                                                          else {}))
        launch = Capability(
            id="", kind=_kind(d.get("kind"), "runtime_launch"), name=f"runtime: {name}",
            description=(str(d.get("description") or "") or f"starts `{_short(cmd, 120)}`")[:300], source="repository",
            confidence=base_conf, provider=self.name, key=key,
            constraints={"lifecycle": "service", "readiness": spec, "ready_timeout_seconds": ready_timeout,
                         "timeout_seconds": 30, "accepts_args": False},
            details={"command": cmd, "cwd": cwd}, reason=runtime_reason, provenance=dict(p))
        caps = [launch]

        def sub(suffix: str, kind: str, cname: str, desc: str, details: dict[str, Any], *, reason: str = "",
                timeout: int = 30, accepts_args: bool = False, extra: dict[str, Any] | None = None) -> Capability:
            bad_reason = reason or (f"its runtime is unavailable: {why}" if why else "")
            return Capability(
                id="", kind=kind, name=cname[:120], description=desc[:300], source="repository",
                confidence=UNAVAILABLE if bad_reason else INFERRED, provider=self.name, key=f"{key}:{suffix}",
                constraints={"lifecycle": "oneshot", "requires_resource": key, "timeout_seconds": timeout,
                             "accepts_args": accepts_args, **(extra or {})},
                details={"runtime": key, **details},
                reason=bad_reason or "observes the declared runtime while it runs", provenance=dict(p))

        caps.append(sub("ready", "runtime_ready", f"{name}: readiness re-check",
                        f"probes again whether {name} is ready ({rd.describe(spec) if spec else 'alive'})",
                        {"readiness": spec}))
        caps.append(sub("alive", "process_control", f"{name}: still running",
                        f"passes while {name} is still running (fails with its exit code if it crashed)", {}))
        logs = []
        for lg in (d.get("logs") or [])[:MAX_PER_RUNTIME]:
            lp = str((lg or {}).get("path") or "") if isinstance(lg, dict) else ""
            if lp and rd.relative_path_ok(lp):
                logs.append(lp.replace("\\", "/"))
            elif lp:
                self.last_notes.append(f"runtime {name}: log path {lp!r} ignored (must be repository-relative)")
        caps.append(sub("log", "runtime_log", f"{name}: output and logs",
                        f"bounded capture of {name}'s output" + (f" and {', '.join(logs)}" if logs else "")
                        + "; use expect_output / fail_output as literal markers", {"logs": logs}))
        for ep in (d.get("endpoints") or [])[:MAX_PER_RUNTIME]:
            if not isinstance(ep, dict):
                continue
            ename, url = str(ep.get("name") or "endpoint").strip()[:40], str(ep.get("url") or "").strip()
            bad_url = rd.check_local_url(url)
            try:
                expected = int(ep.get("expected_status") or 200)
            except (TypeError, ValueError):
                expected = 0
            if not bad_url and not 100 <= expected <= 599:
                bad_url = "expected_status must be an HTTP status code"
            caps.append(sub(f"endpoint:{_slug(ename)}", "local_endpoint", f"{name}: GET {ename}",
                            f"GET {rd.redact_url(url)} expecting HTTP {expected} (optional literal text via "
                            "expect_output)", {"url": url, "expected_status": expected},
                            reason=f"invalid endpoint: {bad_url}" if bad_url else ""))
        for act in (d.get("actions") or [])[:MAX_PER_RUNTIME]:
            if not isinstance(act, dict) or not str(act.get("command") or "").strip():
                continue
            aname, acmd = str(act.get("name") or "action").strip()[:40], str(act["command"]).strip()
            bad_act = f"needs user approval ({destructive_reason(acmd)})" if destructive_reason(acmd) else ""
            if not bad_act and not self._resolve(acmd, os.path.join(ctx.repo_path, cwd) if cwd else ctx.repo_path):
                bad_act = f"program {_program(acmd)!r} not found"
            caps.append(sub(f"action:{_slug(aname)}", _kind(act.get("kind"), "runtime_behavior"), f"{name}: {aname}",
                            str(act.get("description") or f"runs `{_short(acmd, 120)}` while {name} runs"),
                            {"command": acmd, "cwd": cwd}, reason=bad_act,
                            timeout=int(act.get("timeout_seconds") or 120)))
        return caps

    # ------------------------------------------------------------ validation / execution

    def validate(self, cap: Capability, step: PlanStep) -> str:
        if cap.constraints.get("lifecycle") == "service":
            return f"{cap.id} is a runtime: list it under `resources` (it is started and stopped around the steps)"
        if step.args:
            return f"{cap.id} does not accept arguments"
        cmd = str(cap.details.get("command") or "")
        if cmd and destructive_reason(cmd):
            return f"needs user approval ({destructive_reason(cmd)})"
        return ""

    def _handle(self, cap: Capability, ctx: ExecContext) -> Any:
        return ctx.resources.get(str(cap.details.get("runtime") or ""))

    async def execute(self, cap: Capability, step: PlanStep, ctx: ExecContext) -> StepOutcome:
        why = self.validate(cap, step)
        if why:
            return StepOutcome(UNAVAILABLE, reason=why, cause="strategy")
        h = self._handle(cap, ctx)
        if h is None:
            return StepOutcome(UNAVAILABLE, reason="the runtime is not running for this requirement", cause="strategy")
        suffix = cap.key.rsplit(":", 2)
        t0 = time.monotonic()
        if cap.kind == "process_control":
            if h.running:
                up = time.monotonic() - (getattr(h, "started_monotonic", 0.0) or time.monotonic())
                return StepOutcome(PASSED, summary=f"{cap.name}: still running after {up:.1f}s",
                                   duration=time.monotonic() - t0)
            return StepOutcome(FAILED, h.exit_code, summary=f"{cap.name}: the runtime exited with code {h.exit_code}",
                               reason="the runtime is not running any more", output=h.output()[-8000:],
                               duration=time.monotonic() - t0)
        if cap.kind == "runtime_ready":
            spec = dict(cap.details.get("readiness") or {"kind": "process_alive", "settle_seconds": 0.1})
            if spec.get("kind") == "process_alive":
                spec["settle_seconds"] = 0.1
            status, detail = await rd.wait_ready(h, spec, min(ctx.timeout, 10.0), ctx.repo_path)
            return StepOutcome(PASSED if status == "ready" else FAILED, summary=f"{cap.name}: {detail}",
                               reason="" if status == "ready" else f"not ready ({status})",
                               duration=time.monotonic() - t0)
        if cap.kind == "runtime_log":
            parts = [f"=== output of the runtime ===\n{h.output()}"]
            for rel in cap.details.get("logs") or []:
                full = os.path.abspath(os.path.join(ctx.repo_path, *rel.split("/")))
                if full.startswith(os.path.abspath(ctx.repo_path) + os.sep) and os.path.isfile(full):
                    parts.append(f"=== {rel} ===\n{_tail_file(full)}")
                else:
                    parts.append(f"=== {rel} === (not present)")
            text = "\n".join(parts)[-max(2048, ctx.max_capture_bytes):]
            if step.fail_output and step.fail_output in text:
                return StepOutcome(FAILED, summary=f"{cap.name}: the failure marker {step.fail_output!r} appeared",
                                   reason="failure marker found", output=text, duration=time.monotonic() - t0)
            if step.expect_output and step.expect_output not in text:
                return StepOutcome(FAILED, summary=f"{cap.name}: the expected text {step.expect_output!r} did not "
                                                   "appear", reason="expected output missing", output=text,
                                   duration=time.monotonic() - t0)
            return StepOutcome(PASSED, summary=f"{cap.name}: captured ({len(text)} chars)"
                               + (f", contains {step.expect_output!r}" if step.expect_output else "")
                               + (f", no {step.fail_output!r}" if step.fail_output else ""), output=text,
                               duration=time.monotonic() - t0)
        if cap.kind == "local_endpoint":
            url, expected = str(cap.details.get("url") or ""), int(cap.details.get("expected_status") or 200)
            status, body, err = await asyncio.to_thread(rd.http_get, url, min(ctx.timeout, 15.0))
            where = rd.redact_url(url)
            if status is None:
                return StepOutcome(FAILED, summary=f"GET {where}: no answer ({err})", reason="no HTTP answer",
                                   duration=time.monotonic() - t0)
            out = f"HTTP {status}\n{body}"
            if status != expected:
                return StepOutcome(FAILED, summary=f"GET {where}: HTTP {status} (expected {expected})",
                                   reason=f"HTTP {status}", output=out, duration=time.monotonic() - t0)
            if step.fail_output and step.fail_output in body:
                return StepOutcome(FAILED, summary=f"GET {where}: the failure marker {step.fail_output!r} appeared",
                                   reason="failure marker found", output=out, duration=time.monotonic() - t0)
            if step.expect_output and step.expect_output not in body:
                return StepOutcome(FAILED, summary=f"GET {where}: HTTP {status} but {step.expect_output!r} is missing",
                                   reason="expected output missing", output=out, duration=time.monotonic() - t0)
            return StepOutcome(PASSED, summary=f"GET {where}: HTTP {status}"
                               + (f" and contains {step.expect_output!r}" if step.expect_output else ""),
                               output=out, duration=time.monotonic() - t0, details={"http_status": status})
        if cap.details.get("command"):  # a declared action, run while the runtime is up
            cwd = cap.details.get("cwd") or ""
            out = await run_command(str(cap.details["command"]), step, ctx,
                                    cwd=os.path.join(ctx.repo_path, cwd) if cwd else "")
            if out.status == PASSED and not h.running:
                out.status, out.reason = FAILED, "the runtime crashed while the action ran"
                out.summary = f"{out.summary}; but the runtime exited with code {h.exit_code}"
            return out
        return StepOutcome(UNAVAILABLE, reason=f"unknown runtime capability {suffix[-1]}", cause="strategy")

    # ------------------------------------------------------------ lifecycle

    def supports_lifecycle(self, cap: Capability) -> bool:
        return cap.constraints.get("lifecycle") == "service"

    async def start(self, cap: Capability, ctx: ExecContext) -> ServiceProcess:
        cmd = str(cap.details.get("command") or "")
        if destructive_reason(cmd):
            raise RuntimeError(f"needs user approval ({destructive_reason(cmd)})")
        cwd = cap.details.get("cwd") or ""
        sp = ServiceProcess(cmd, os.path.join(ctx.repo_path, cwd) if cwd else ctx.repo_path, ctx.max_capture_bytes)
        spec = cap.constraints.get("readiness") or {}
        await sp.start([str(spec.get("text") or "")] if spec.get("kind") == "stdout_contains" else [])
        return sp

    async def ready(self, handle: ServiceProcess, cap: Capability, ctx: ExecContext) -> tuple[str, str]:
        declared = float(cap.constraints.get("ready_timeout_seconds") or ctx.ready_timeout)
        spec = cap.constraints.get("readiness") or {"kind": "process_alive", "settle_seconds": 1.0}
        return await rd.wait_ready(handle, spec, min(declared, ctx.ready_timeout), ctx.repo_path)

    def capture(self, handle: ServiceProcess) -> str:
        return handle.output()

    async def stop(self, handle: ServiceProcess) -> None:
        await handle.stop()
